#!/usr/bin/env python3
"""Fit and audit V8 tactical macro-option critics on isolated splits."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
from pathlib import Path

import numpy as np
import torch

from benchmarks.collect_drvoi_v8_macro_option_data import REPRESENTATION_KEYS
from benchmarks.drvoi.q_model import MacroOptionDuelingQ


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--train", type=Path, nargs="+", required=True)
    parser.add_argument("--validation", type=Path, nargs="+", required=True)
    parser.add_argument("--config", type=Path, default=Path(
        "configs/drvoi_rhppo_v8_macro_option.json"))
    parser.add_argument("--seed", type=int, default=77185)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def target_keys(protocol):
    keys = []
    for horizon in protocol["data"]["return_horizons"]:
        keys.extend((f"return_{horizon}", f"bootstrap_return_{horizon}"))
    if protocol["data"]["include_full_episode_return"]:
        keys.append("return_full")
    return tuple(keys)


def load_split(paths, expected_split, config_hash, targets):
    keys = (*REPRESENTATION_KEYS, *targets, "legal", "collection_seed",
            "warmup_decisions", "learner_side", "opponent_kind")
    values = {key: [] for key in keys}
    seeds = set()
    reports = []
    for path in paths:
        payload = torch.load(path, map_location="cpu", weights_only=False)
        report = payload["report"]
        if report.get("split") != expected_split:
            raise ValueError(f"{path} is not {expected_split} data")
        if report.get("config_sha256") != config_hash:
            raise ValueError(f"{path} was generated by a different config")
        seeds.add(int(report["collection_seed"]))
        reports.append(report)
        for key in keys:
            values[key].append(payload["data"][key])
    return ({key: torch.cat(parts) for key, parts in values.items()},
            sorted(seeds), reports)


def macro_option_loss(prediction, truth, legal, cfg):
    selected_prediction = prediction[legal]
    selected_truth = truth[legal]
    raw = torch.nn.functional.smooth_l1_loss(
        selected_prediction, selected_truth)
    count = legal.sum(-1).clamp_min(1)
    pred_mean = (prediction * legal).sum(-1) / count
    true_mean = (truth * legal).sum(-1) / count
    true_max = truth.masked_fill(~legal, -torch.inf).max(-1).values
    true_min = truth.masked_fill(~legal, torch.inf).min(-1).values
    value_range = (true_max - true_min).clamp_min(1.0e-2)
    pred_advantage = (prediction - pred_mean[:, None]) / value_range[:, None]
    true_advantage = (truth - true_mean[:, None]) / value_range[:, None]
    centered = torch.nn.functional.smooth_l1_loss(
        pred_advantage[legal], true_advantage[legal])
    temperature = cfg["soft_rank_temperature"]
    pred_logits = (prediction / temperature).masked_fill(~legal, -1.0e9)
    true_logits = (truth / temperature).masked_fill(~legal, -1.0e9)
    target_probability = torch.softmax(true_logits, -1)
    soft_rank = torch.nn.functional.kl_div(
        torch.log_softmax(pred_logits, -1), target_probability,
        reduction="batchmean")
    total = (
        cfg["raw_value_loss_weight"] * raw
        + cfg["centered_advantage_loss_weight"] * centered
        + cfg["soft_rank_loss_weight"] * soft_rank)
    return total, {"raw": raw, "centered": centered, "soft_rank": soft_rank}


def _bootstrap_mean(values, seed, samples):
    array = np.asarray(values, dtype=np.float64)
    if array.size == 0:
        return float("nan"), [float("nan"), float("nan")]
    rng = np.random.default_rng(seed)
    estimates = np.empty(samples, dtype=np.float64)
    for index in range(samples):
        estimates[index] = rng.choice(array, array.size, replace=True).mean()
    return float(array.mean()), np.quantile(estimates, [0.025, 0.975]).tolist()


@torch.no_grad()
def option_metrics(prediction, truth, legal, cfg, seed):
    pair_accuracy = []
    normalized_regret = []
    absolute_regret = []
    top2_regret = []
    random_regret = []
    ranges = []
    details = []
    rng = np.random.default_rng(seed)
    for context in range(truth.shape[0]):
        selected = torch.nonzero(legal[context]).flatten()
        true = truth[context, selected]
        pred = prediction[context, selected]
        value_range = float(true.max() - true.min())
        valid_context = value_range >= cfg["minimum_value_range"]
        if not valid_context:
            details.append({
                "context": context, "legal_options": int(selected.numel()),
                "value_range": value_range, "valid_value_range": False})
            continue
        left, right = torch.triu_indices(
            selected.numel(), selected.numel(), 1, device=true.device)
        true_gap = true[left] - true[right]
        pred_gap = pred[left] - pred[right]
        valid_pair = true_gap.abs() >= (
            cfg["minimum_pair_gap_fraction"] * value_range)
        accuracy = float(
            ((true_gap[valid_pair] * pred_gap[valid_pair]) > 0).float().mean()
        ) if bool(valid_pair.any()) else float("nan")
        chosen = int(pred.argmax())
        regret = float(true.max() - true[chosen])
        top_count = min(2, selected.numel())
        top_indices = pred.topk(top_count).indices
        top_regret = float(true.max() - true[top_indices].max())
        random_choice = int(rng.integers(0, selected.numel()))
        random_value = float(true.max() - true[random_choice]) / value_range
        if math.isfinite(accuracy):
            pair_accuracy.append(accuracy)
        normalized_regret.append(regret / value_range)
        absolute_regret.append(regret)
        top2_regret.append(top_regret / value_range)
        random_regret.append(random_value)
        ranges.append(value_range)
        details.append({
            "context": context, "legal_options": int(selected.numel()),
            "value_range": value_range, "valid_value_range": True,
            "valid_pairs": int(valid_pair.sum()),
            "pairwise_accuracy": accuracy,
            "absolute_regret": regret,
            "normalized_regret": regret / value_range,
            "top2_normalized_regret": top_regret / value_range,
            "predicted_option": int(selected[chosen]),
            "truth_option": int(selected[true.argmax()]),
        })
    pair_mean, pair_ci = _bootstrap_mean(
        pair_accuracy, seed + 1, cfg["bootstrap_samples"])
    regret_mean, regret_ci = _bootstrap_mean(
        normalized_regret, seed + 2, cfg["bootstrap_samples"])
    weighted = (
        float(np.sum(absolute_regret) / np.sum(ranges))
        if ranges and np.sum(ranges) > 0 else float("nan"))
    return {
        "pairwise_accuracy": pair_mean,
        "pairwise_accuracy_ci95": pair_ci,
        "normalized_argmax_regret": regret_mean,
        "normalized_argmax_regret_ci95": regret_ci,
        "weighted_normalized_argmax_regret": weighted,
        "mean_absolute_regret": float(np.mean(absolute_regret))
        if absolute_regret else float("nan"),
        "top2_normalized_regret": float(np.mean(top2_regret))
        if top2_regret else float("nan"),
        "random_normalized_regret": float(np.mean(random_regret))
        if random_regret else float("nan"),
        "valid_context_fraction": len(ranges) / max(truth.shape[0], 1),
        "mean_value_range": float(np.mean(ranges)) if ranges else float("nan"),
        "contexts": details,
    }


@torch.no_grad()
def evaluate(model, context, truth, legal, metrics_cfg, seed):
    prediction = model.all_options(context, legal)
    metrics = option_metrics(prediction, truth, legal, metrics_cfg, seed)
    metrics["mc_mse"] = float(torch.nn.functional.mse_loss(
        prediction[legal], truth[legal]))
    return metrics


def selection_score(metrics):
    """Prefer decision metrics, but keep tiny smoke sets diagnosable."""
    pair = metrics["pairwise_accuracy"]
    regret = metrics["weighted_normalized_argmax_regret"]
    if math.isfinite(pair) and math.isfinite(regret):
        return regret + 1.0 - pair, "decision_metrics"
    # No valid-value context is expected in some tiny smoke samples.  MSE is
    # only an engineering fallback so the pipeline can emit a full report; it
    # is never labeled evidence that an option-value target is useful.
    return 10.0 + metrics["mc_mse"], "smoke_mse_fallback"


def train_model(train_context, validation_context, train_target,
                validation_target, cfg, metrics_cfg, seed):
    mean = train_context.mean(0)
    scale = train_context.std(0, unbiased=False).clamp_min(1.0e-5)
    train_context = (train_context - mean) / scale
    validation_context = (validation_context - mean) / scale
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    model = MacroOptionDuelingQ(
        train_context.shape[-1], train_target["return"].shape[-1],
        cfg["hidden_size"]).to(train_context.device)
    optimizer = torch.optim.Adam(model.parameters(), lr=cfg["learning_rate"])
    generator = torch.Generator(device=train_context.device).manual_seed(seed + 1)
    best_score, best_state, best_epoch, stale = math.inf, None, 0, 0
    history = []
    for epoch in range(1, cfg["epochs"] + 1):
        order = torch.randperm(
            train_context.shape[0], device=train_context.device,
            generator=generator)
        losses = []
        for start in range(0, order.numel(), cfg["batch_contexts"]):
            index = order[start:start + cfg["batch_contexts"]]
            prediction = model.all_options(
                train_context[index], train_target["legal"][index])
            loss, _ = macro_option_loss(
                prediction, train_target["return"][index],
                train_target["legal"][index], cfg)
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 10.0)
            optimizer.step()
            losses.append(float(loss.detach()))
        metrics = evaluate(
            model, validation_context, validation_target["return"],
            validation_target["legal"], metrics_cfg, seed + epoch)
        score, score_basis = selection_score(metrics)
        history.append({
            "epoch": epoch, "train_loss": float(np.mean(losses)),
            "validation_pairwise_accuracy": metrics["pairwise_accuracy"],
            "validation_weighted_normalized_argmax_regret": metrics[
                "weighted_normalized_argmax_regret"],
            "selection_score": score,
            "selection_score_basis": score_basis,
        })
        if math.isfinite(score) and score < best_score - 1.0e-5:
            best_score = score
            best_state = copy.deepcopy(model.state_dict())
            best_epoch = epoch
            stale = 0
        else:
            stale += 1
            if stale >= cfg["patience"]:
                break
    if best_state is None:
        raise RuntimeError("no finite validation score was produced")
    model.load_state_dict(best_state)
    return ({
        "best_epoch": best_epoch,
        "final_epoch": history[-1]["epoch"],
        "history": history,
        "best_train_metrics": evaluate(
            model, train_context, train_target["return"],
            train_target["legal"], metrics_cfg, seed + 10000),
        "best_validation_metrics": evaluate(
            model, validation_context, validation_target["return"],
            validation_target["legal"], metrics_cfg, seed + 11000),
    }, {"model": best_state, "mean": mean.cpu(), "scale": scale.cpu()})


def guidance(metrics, protocol):
    cfg = protocol["screening_guidance"]
    promising = (
        metrics["pairwise_accuracy"] >= cfg["pairwise_accuracy_promising"]
        and metrics["weighted_normalized_argmax_regret"]
        <= cfg["weighted_normalized_regret_promising"])
    return "PROMISING" if promising else "NEEDS_ITERATION"


def main():
    args = parse_args()
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required")
    protocol = json.loads(args.config.read_text(encoding="utf-8"))
    config_hash = sha256(args.config)
    targets = target_keys(protocol)
    train, train_seeds, train_reports = load_split(
        args.train, "train", config_hash, targets)
    validation, validation_seeds, validation_reports = load_split(
        args.validation, "validation", config_hash, targets)
    device = torch.device("cuda")
    for data in (train, validation):
        for key in (*REPRESENTATION_KEYS, *targets, "legal"):
            data[key] = data[key].to(device)

    reports = {}
    artifacts = {}
    best = None
    best_deployable = None
    for target_index, target in enumerate(targets):
        reports[target] = {}
        artifacts[target] = {}
        for representation_index, representation in enumerate(REPRESENTATION_KEYS):
            report, artifact = train_model(
                train[representation], validation[representation],
                {"return": train[target], "legal": train["legal"]},
                {"return": validation[target], "legal": validation["legal"]},
                protocol["critic"], protocol["metrics"],
                args.seed + target_index * 10000 + representation_index * 1000)
            metrics = report["best_validation_metrics"]
            report["guidance"] = guidance(metrics, protocol)
            report["dimension"] = int(train[representation].shape[-1])
            reports[target][representation] = report
            artifacts[target][representation] = artifact
            score, score_basis = selection_score(metrics)
            report["selection_score_basis"] = score_basis
            candidate = (score, target, representation, report["guidance"])
            if best is None or candidate[0] < best[0]:
                best = candidate
            if (representation == "registered_v7_1"
                    and (best_deployable is None
                         or candidate[0] < best_deployable[0])):
                best_deployable = candidate
            print(json.dumps({
                "target": target, "representation": representation,
                "pairwise_accuracy": metrics["pairwise_accuracy"],
                "weighted_normalized_argmax_regret": metrics[
                    "weighted_normalized_argmax_regret"],
                "top2_normalized_regret": metrics["top2_normalized_regret"],
                "valid_context_fraction": metrics["valid_context_fraction"],
                "guidance": report["guidance"],
            }), flush=True)

    summary = {
        "suite": "DRVOI-RHPPO-V8-macro-option-value-development",
        "protocol_version": protocol["protocol_version"],
        "scientific_result": False,
        "selection_uses_validation": True,
        "train_seeds": train_seeds,
        "validation_seeds": validation_seeds,
        "train_contexts": int(train["legal"].shape[0]),
        "validation_contexts": int(validation["legal"].shape[0]),
        "collection_reports": {
            "train": train_reports, "validation": validation_reports},
        "results": reports,
        "recommended_development_target": {
            "target": best[1], "representation": best[2],
            "guidance": best[3], "selection_score": best[0]},
        "recommended_deployable_target": {
            "target": best_deployable[1],
            "representation": best_deployable[2],
            "guidance": best_deployable[3],
            "selection_score": best_deployable[0]},
        "long_training_started": False,
        "note": (
            "Guidance is developmental, not a hard authorization gate. "
            "Independent test data remains untouched."),
        "config_sha256": config_hash,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    torch.save({
        "protocol_version": protocol["protocol_version"],
        "artifacts": artifacts,
        "recommended_development_target": summary[
            "recommended_development_target"],
        "recommended_deployable_target": summary[
            "recommended_deployable_target"],
    }, args.output.with_suffix(".pt"))
    print(json.dumps(summary["recommended_development_target"], indent=2))


if __name__ == "__main__":
    main()
