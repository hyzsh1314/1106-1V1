#!/usr/bin/env python3
"""Screen V7.2 future-state representations against shared MC action truth."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
from pathlib import Path

import numpy as np
import torch

from benchmarks.calibrate_drvoi_v7_1_p1q_mc import calibration_loss
from benchmarks.collect_drvoi_v7_2_state_sufficiency_data import (
    REPRESENTATION_KEYS,
)
from benchmarks.validate_drvoi_v7_1_p1q_development import build_q_model
from benchmarks.validate_drvoi_v7_1_p1q_mc_probe import per_probe_metrics


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--train", type=Path, nargs="+", required=True)
    parser.add_argument("--validation", type=Path, nargs="+", required=True)
    parser.add_argument("--config", type=Path, default=Path(
        "configs/drvoi_rhppo_v7_2_state_sufficiency.json"))
    parser.add_argument("--seed", type=int, default=57185)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_split(paths, split, config_hash):
    keys = (*REPRESENTATION_KEYS, "return", "legal", "collection_seed",
            "warmup_decisions", "learner_side", "opponent_kind")
    values = {key: [] for key in keys}
    seeds = set()
    for path in paths:
        payload = torch.load(path, map_location="cpu", weights_only=False)
        report = payload["report"]
        if (report.get("split") != split
                or report.get("contains_formal_test", True)):
            raise ValueError(f"{path} is not isolated {split} data")
        if report.get("config_sha256") != config_hash:
            raise ValueError(f"{path} was generated by a different config")
        seeds.add(int(report["collection_seed"]))
        for key in keys:
            values[key].append(payload["data"][key])
    return {key: torch.cat(parts) for key, parts in values.items()}, sorted(seeds)


@torch.no_grad()
def evaluate(model, context, truth, legal, seed):
    prediction = model.all_actions(context)
    metrics = per_probe_metrics(
        prediction, truth, legal, minimum_gap=0.05, seed=seed)
    metrics["mc_mse"] = float(torch.nn.functional.mse_loss(
        prediction[legal], truth[legal]))
    return metrics


def gate_metrics(metrics, cfg):
    return {
        "pairwise_action_ranking": {
            "pass": (metrics["pairwise_accuracy"]
                     >= cfg["pairwise_accuracy_min"]
                     and metrics["pairwise_accuracy_ci95"][0]
                     > cfg["pairwise_accuracy_ci_lower_min"])},
        "normalized_argmax_regret": {
            "pass": metrics["normalized_argmax_regret"]
            <= cfg["normalized_argmax_regret_max"]},
        "random_action_control": {
            "pass": metrics["normalized_argmax_regret"]
            < metrics["random_normalized_argmax_regret"]},
    }


def decide(representation_gates, representations):
    passed = {
        key: all(item["pass"] for item in gates.values())
        for key, gates in representation_gates.items()}
    if not passed["mechanistic_oracle"]:
        return "STATE_TARGET_NO_GO", False
    deployable = [
        key for key, value in representations.items()
        if value.get("deployable", False)]
    if not any(passed[key] for key in deployable):
        return "NEW_PREDICTOR_REQUIRED", False
    return "DEPLOYABLE_REPRESENTATION_FOUND", True


def train_representation(name, train_context, validation_context,
                         train, validation, architecture, cfg, seed):
    device = train_context.device
    mean = train_context.mean(0)
    scale = train_context.std(0, unbiased=False).clamp_min(1.0e-5)
    train_context = (train_context - mean) / scale
    validation_context = (validation_context - mean) / scale
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    model = build_q_model(train_context.shape[-1], architecture).to(device)
    optimizer = torch.optim.Adam(
        model.parameters(), lr=cfg["learning_rate"])
    generator = torch.Generator(device=device).manual_seed(seed + 1)
    best_score, best_state, best_epoch, stale = math.inf, None, 0, 0
    history = []
    for epoch in range(1, cfg["epochs"] + 1):
        order = torch.randperm(
            train_context.shape[0], device=device, generator=generator)
        losses = []
        for start in range(0, order.numel(), cfg["batch_contexts"]):
            index = order[start:start + cfg["batch_contexts"]]
            prediction = model.all_actions(train_context[index])
            loss, _ = calibration_loss(
                prediction, train["return"][index], train["legal"][index], cfg)
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            norm = torch.nn.utils.clip_grad_norm_(model.parameters(), 10.0)
            if not math.isfinite(float(norm)):
                raise FloatingPointError(f"non-finite {name} gradient")
            optimizer.step()
            losses.append(float(loss.detach()))
        metrics = evaluate(
            model, validation_context, validation["return"],
            validation["legal"], seed + epoch)
        score = (metrics["normalized_argmax_regret"]
                 + 1.0 - metrics["pairwise_accuracy"])
        history.append({
            "epoch": epoch,
            "train_loss": float(np.mean(losses)),
            "validation_pairwise_accuracy": metrics["pairwise_accuracy"],
            "validation_normalized_argmax_regret": metrics[
                "normalized_argmax_regret"],
            "validation_mc_mse": metrics["mc_mse"],
            "selection_score": score,
        })
        if score < best_score - 1.0e-5:
            best_score = score
            best_state = copy.deepcopy(model.state_dict())
            best_epoch = epoch
            stale = 0
        else:
            stale += 1
            if stale >= cfg["patience"]:
                break
    final_train = evaluate(
        model, train_context, train["return"], train["legal"], seed + 8000)
    final_validation = evaluate(
        model, validation_context, validation["return"],
        validation["legal"], seed + 9000)
    model.load_state_dict(best_state)
    best_train = evaluate(
        model, train_context, train["return"], train["legal"], seed + 10000)
    best_validation = evaluate(
        model, validation_context, validation["return"],
        validation["legal"], seed + 11000)
    return {
        "representation": name,
        "dimension": int(train_context.shape[-1]),
        "best_epoch": best_epoch,
        "final_epoch": history[-1]["epoch"],
        "history": history,
        "best_train_metrics": best_train,
        "best_validation_metrics": best_validation,
        "final_train_metrics": final_train,
        "final_validation_metrics": final_validation,
    }, {"model": best_state, "mean": mean.cpu(), "scale": scale.cpu()}


def main():
    args = parse_args()
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required")
    protocol = json.loads(args.config.read_text(encoding="utf-8"))
    config_hash = sha256(args.config)
    train, train_seeds = load_split(args.train, "train", config_hash)
    validation, validation_seeds = load_split(
        args.validation, "validation", config_hash)
    data_cfg = protocol["data"]
    if train_seeds != sorted(data_cfg["train_seeds"]):
        raise ValueError("train seeds do not match V7.2 freeze")
    if validation_seeds != sorted(data_cfg["validation_seeds"]):
        raise ValueError("validation seeds do not match V7.2 freeze")
    device = torch.device("cuda")
    for data in (train, validation):
        for key in (*REPRESENTATION_KEYS, "return", "legal"):
            data[key] = data[key].to(device)
    architecture = protocol["critic"]["architecture"]
    reports, artifacts, representation_gates = {}, {}, {}
    for index, name in enumerate(REPRESENTATION_KEYS):
        report, artifact = train_representation(
            name, train[name], validation[name], train, validation,
            architecture, protocol["critic"], args.seed + 1000 * index)
        gates = gate_metrics(
            report["best_validation_metrics"], protocol["gates"])
        report["gates"] = gates
        report["all_gates_pass"] = all(
            item["pass"] for item in gates.values())
        reports[name] = report
        artifacts[name] = artifact
        representation_gates[name] = gates
        print(json.dumps({
            "representation": name,
            "pairwise_accuracy": report["best_validation_metrics"][
                "pairwise_accuracy"],
            "normalized_argmax_regret": report["best_validation_metrics"][
                "normalized_argmax_regret"],
            "all_gates_pass": report["all_gates_pass"],
        }), flush=True)
    decision, response_development_authorized = decide(
        representation_gates, protocol["representations"])
    summary = {
        "suite": "DRVOI-RHPPO-V7.2-state-sufficiency-development",
        "protocol_version": protocol["protocol_version"],
        "scientific_result": False,
        "formal_test_accessed": False,
        "train_seeds": train_seeds,
        "validation_seeds": validation_seeds,
        "train_contexts": int(train["return"].shape[0]),
        "validation_contexts": int(validation["return"].shape[0]),
        "architecture": architecture,
        "representations": reports,
        "decision": decision,
        "response_development_authorized": response_development_authorized,
        "formal_test_generation_authorized": False,
        "p1q_authorized": False,
        "o0_authorized": False,
        "long_training_authorized": False,
        "config_sha256": config_hash,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    torch.save({
        "protocol_version": protocol["protocol_version"],
        "architecture": architecture,
        "representations": artifacts,
        "decision": decision,
    }, args.output.with_suffix(".pt"))
    print(json.dumps({
        "decision": decision,
        "response_development_authorized": response_development_authorized,
    }))
    if not response_development_authorized:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
