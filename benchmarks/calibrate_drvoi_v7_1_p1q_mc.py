#!/usr/bin/env python3
"""Calibrate the frozen V7.1 TD critic on isolated all-action MC data."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
from pathlib import Path

import numpy as np
import torch

from benchmarks.validate_drvoi_v7_1_p1q_development import build_q_model
from benchmarks.validate_drvoi_v7_1_p1q_mc_probe import per_probe_metrics


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--q-artifact", type=Path, required=True)
    parser.add_argument("--train", type=Path, nargs="+", required=True)
    parser.add_argument("--validation", type=Path, nargs="+", required=True)
    parser.add_argument("--config", type=Path, default=Path(
        "configs/drvoi_rhppo_v7_1_p1q.json"))
    parser.add_argument("--seed", type=int, default=47185)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def file_sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_split(paths, expected_split, expected_config_sha256=None):
    values = {key: [] for key in (
        "context", "return", "legal", "collection_seed",
        "warmup_decisions", "learner_side", "opponent_kind")}
    seeds = set()
    for path in paths:
        payload = torch.load(path, map_location="cpu", weights_only=False)
        report = payload["report"]
        if report.get("split") != expected_split or report.get(
                "contains_formal_test", True):
            raise ValueError(
                f"{path} is not isolated {expected_split} MC data")
        if (expected_config_sha256 is not None
                and report.get("config_sha256") != expected_config_sha256):
            raise ValueError(f"{path} was generated by a different config")
        seeds.add(int(report["collection_seed"]))
        for key in values:
            values[key].append(payload["data"][key])
    return {key: torch.cat(parts) for key, parts in values.items()}, sorted(seeds)


def calibration_loss(prediction, truth, legal, cfg):
    selected_prediction = prediction[legal]
    selected_truth = truth[legal]
    raw = torch.nn.functional.smooth_l1_loss(
        selected_prediction, selected_truth)
    count = legal.sum(-1).clamp_min(1)
    pred_mean = (prediction * legal).sum(-1) / count
    true_mean = (truth * legal).sum(-1) / count
    true_max = truth.masked_fill(~legal, -torch.inf).max(-1).values
    true_min = truth.masked_fill(~legal, torch.inf).min(-1).values
    value_range = (true_max - true_min).clamp_min(0.05)
    pred_advantage = (prediction - pred_mean[:, None]) / value_range[:, None]
    true_advantage = (truth - true_mean[:, None]) / value_range[:, None]
    centered = torch.nn.functional.smooth_l1_loss(
        pred_advantage[legal], true_advantage[legal])
    temperature = cfg["soft_argmax_temperature"]
    pred_logits = (prediction / temperature).masked_fill(~legal, -1.0e9)
    true_logits = (truth / temperature).masked_fill(~legal, -1.0e9)
    target_probability = torch.softmax(true_logits, -1)
    soft_argmax = torch.nn.functional.kl_div(
        torch.log_softmax(pred_logits, -1), target_probability,
        reduction="batchmean")
    total = (
        cfg["raw_value_loss_weight"] * raw
        + cfg["centered_advantage_loss_weight"] * centered
        + cfg["soft_argmax_loss_weight"] * soft_argmax)
    return total, {"raw": raw, "centered": centered,
                   "soft_argmax": soft_argmax}


@torch.no_grad()
def evaluate(model, data, cfg, seed):
    prediction = model.all_actions(data["context"])
    metrics = per_probe_metrics(
        prediction, data["return"], data["legal"],
        minimum_gap=0.05, seed=seed)
    metrics["mc_mse"] = float(torch.nn.functional.mse_loss(
        prediction[data["legal"]], data["return"][data["legal"]]))
    return metrics


@torch.no_grad()
def nearest_neighbor_controls(train, validation, seed):
    controls = {}
    for feature_name, feature_slice in (
            ("full_context", slice(None)),
            ("response_only", slice(-12, None))):
        distance = torch.cdist(
            validation["context"][:, feature_slice],
            train["context"][:, feature_slice])
        for neighbors in (1, 4, 8):
            index = distance.topk(neighbors, largest=False).indices
            prediction = train["return"][index].mean(1)
            controls[f"{feature_name}_k{neighbors}"] = per_probe_metrics(
                prediction, validation["return"], validation["legal"],
                minimum_gap=0.05, seed=seed + neighbors)
    return controls


def main():
    args = parse_args()
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required")
    protocol = json.loads(args.config.read_text(encoding="utf-8"))
    cfg = protocol["mc_calibration"]
    config_sha256 = file_sha256(args.config)
    train, train_seeds = load_split(
        args.train, "train", config_sha256)
    validation, validation_seeds = load_split(
        args.validation, "validation", config_sha256)
    if train_seeds != sorted(cfg["train_seeds"]):
        raise ValueError("MC train seeds do not match frozen configuration")
    if validation_seeds != sorted(cfg["validation_seeds"]):
        raise ValueError("MC validation seeds do not match frozen configuration")
    payload = torch.load(args.q_artifact, map_location="cpu", weights_only=False)
    architecture = payload["architecture"]
    selected = payload["selected"]
    device = torch.device("cuda")
    model = build_q_model(payload["context_dim"], architecture).to(device)
    model.load_state_dict(payload["models"][selected])
    mean = payload["context_mean"].to(device)
    scale = payload["context_scale"].to(device)
    for data in (train, validation):
        data["context"] = ((data["context"].to(device) - mean) / scale)
        data["return"] = data["return"].to(device)
        data["legal"] = data["legal"].to(device)
    torch.manual_seed(args.seed)
    torch.cuda.manual_seed_all(args.seed)
    generator = torch.Generator(device=device).manual_seed(args.seed + 1)
    optimizer = torch.optim.Adam(
        model.parameters(), lr=cfg["learning_rate"])
    best_score, best_state, best_epoch, stale = math.inf, None, 0, 0
    history = []
    for epoch in range(1, cfg["epochs"] + 1):
        order = torch.randperm(
            train["context"].shape[0], device=device, generator=generator)
        components = {key: [] for key in ("total", "raw", "centered", "soft_argmax")}
        for start in range(0, order.numel(), cfg["batch_contexts"]):
            index = order[start:start + cfg["batch_contexts"]]
            prediction = model.all_actions(train["context"][index])
            loss, parts = calibration_loss(
                prediction, train["return"][index], train["legal"][index], cfg)
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            norm = torch.nn.utils.clip_grad_norm_(model.parameters(), 10.0)
            if not math.isfinite(float(norm)):
                raise FloatingPointError("non-finite MC calibration gradient")
            optimizer.step()
            components["total"].append(float(loss.detach()))
            for key, value in parts.items():
                components[key].append(float(value.detach()))
        metrics = evaluate(model, validation, cfg, args.seed + epoch)
        # Selection is entirely validation based and prioritizes the two
        # pre-registered same-context action semantics.
        score = (metrics["normalized_argmax_regret"]
                 + 1.0 - metrics["pairwise_accuracy"])
        entry = {
            "epoch": epoch,
            **{f"train_{key}": float(np.mean(value))
               for key, value in components.items()},
            "validation_pairwise_accuracy": metrics["pairwise_accuracy"],
            "validation_normalized_argmax_regret": metrics[
                "normalized_argmax_regret"],
            "validation_mc_mse": metrics["mc_mse"],
            "selection_score": score,
        }
        history.append(entry)
        if score < best_score - 1.0e-5:
            best_score = score
            best_state = copy.deepcopy(model.state_dict())
            best_epoch = epoch
            stale = 0
        else:
            stale += 1
            if stale >= cfg["patience"]:
                break
    final_epoch_train_metrics = evaluate(
        model, train, cfg, args.seed + 8000)
    final_epoch_validation_metrics = evaluate(
        model, validation, cfg, args.seed + 9000)
    model.load_state_dict(best_state)
    metrics = evaluate(model, validation, cfg, args.seed + 10000)
    train_metrics = evaluate(model, train, cfg, args.seed + 11000)
    neighbor_controls = nearest_neighbor_controls(
        train, validation, args.seed + 12000)
    gate = protocol["wvr_value_gate"]
    gates = {
        "pairwise_action_ranking": {"pass": (
            metrics["pairwise_accuracy"] >= gate["pairwise_accuracy_min"]
            and metrics["pairwise_accuracy_ci95"][0]
            > gate["pairwise_accuracy_ci_lower_min"])},
        "normalized_argmax_regret": {"pass": (
            metrics["normalized_argmax_regret"]
            <= gate["normalized_argmax_regret_max"])},
        "random_action_control": {"pass": (
            metrics["normalized_argmax_regret"]
            < metrics["random_normalized_argmax_regret"])},
    }
    passed = all(item["pass"] for item in gates.values())
    report = {
        "suite": "DRVOI-RHPPO-V7.1-P1Q-MC-calibration-development",
        "protocol_version": protocol["protocol_version"],
        "scientific_result": False,
        "formal_q_test_accessed": False,
        "architecture": architecture,
        "selected_target_update_epochs": int(selected),
        "train_seeds": train_seeds,
        "validation_seeds": validation_seeds,
        "train_contexts": int(train["context"].shape[0]),
        "validation_contexts": int(validation["context"].shape[0]),
        "best_epoch": best_epoch,
        "final_epoch": history[-1]["epoch"],
        "history": history,
        "final_epoch_train_metrics": final_epoch_train_metrics,
        "final_epoch_validation_metrics": final_epoch_validation_metrics,
        "train_metrics": train_metrics,
        "validation_metrics": metrics,
        "nearest_neighbor_controls": neighbor_controls,
        "gates": gates,
        "all_development_gates_pass": passed,
        "fixed_probe_required": True,
        "formal_test_generation_authorized": False,
        "o0_authorized": False,
        "long_training_authorized": False,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    torch.save({
        "selected": selected,
        "models": {selected: best_state},
        "architecture": architecture,
        "context_mean": payload["context_mean"],
        "context_scale": payload["context_scale"],
        "context_dim": payload["context_dim"],
        "mc_calibrated": True,
        "mc_calibration_best_epoch": best_epoch,
    }, args.output.with_suffix(".pt"))
    print(json.dumps(report, indent=2))
    if not passed:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
