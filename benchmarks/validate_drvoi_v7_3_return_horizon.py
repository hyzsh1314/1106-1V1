#!/usr/bin/env python3
"""Find the largest learnable and response-predictable V7.3 return horizon."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import torch

from benchmarks.collect_drvoi_v7_3_return_horizon_data import (
    REPRESENTATION_KEYS,
)
from benchmarks.validate_drvoi_v7_2_state_sufficiency import (
    gate_metrics,
    train_representation,
)


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--train", type=Path, nargs="+", required=True)
    parser.add_argument("--validation", type=Path, nargs="+", required=True)
    parser.add_argument("--config", type=Path, default=Path(
        "configs/drvoi_rhppo_v7_3_return_horizon.json"))
    parser.add_argument("--seed", type=int, default=67185)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def target_key(horizon):
    return "return_full" if horizon == "full" else f"return_{horizon}"


def load_split(paths, split, config_hash, horizons):
    target_keys = tuple(target_key(value) for value in horizons)
    keys = (*REPRESENTATION_KEYS, *target_keys, "legal", "collection_seed",
            "warmup_decisions", "learner_side", "opponent_kind")
    values = {key: [] for key in keys}
    seeds = set()
    for path in paths:
        payload = torch.load(path, map_location="cpu", weights_only=False)
        report = payload["report"]
        if (report.get("split") != split
                or report.get("contains_formal_test", True)):
            raise ValueError(f"{path} is not isolated {split} data")
        if report.get("config_sha256") != config_hash:
            raise ValueError(f"{path} was generated by a different config")
        seeds.add(int(report["collection_seed"]))
        for key in keys:
            values[key].append(payload["data"][key])
    return {key: torch.cat(parts) for key, parts in values.items()}, sorted(seeds)


def all_pass(gates):
    return all(item["pass"] for item in gates.values())


def decide(pass_matrix, minimum_horizon):
    order = [3, 12, 30, 120, "full"]
    oracle_passing = [
        value for value in order
        if pass_matrix["mechanistic_oracle"].get(str(value), False)]
    if not oracle_passing:
        return "RETURN_TARGET_NO_GO", None, False
    research_oracle = [
        value for value in oracle_passing
        if value == "full" or int(value) >= minimum_horizon]
    if not research_oracle:
        return "MYOPIC_ONLY_NO_GO", None, False
    common = [
        value for value in research_oracle
        if pass_matrix["full_observation"].get(str(value), False)]
    if not common:
        return "REPRESENTATION_PREDICTOR_REQUIRED", None, False
    selected = max(common, key=lambda value: order.index(value))
    return "HORIZON_FOUND", selected, True


def main():
    args = parse_args()
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required")
    protocol = json.loads(args.config.read_text(encoding="utf-8"))
    config_hash = sha256(args.config)
    horizons = [*protocol["data"]["return_horizons"], "full"]
    train, train_seeds = load_split(
        args.train, "train", config_hash, horizons)
    validation, validation_seeds = load_split(
        args.validation, "validation", config_hash, horizons)
    data_cfg = protocol["data"]
    if train_seeds != sorted(data_cfg["train_seeds"]):
        raise ValueError("train seeds do not match V7.3 freeze")
    if validation_seeds != sorted(data_cfg["validation_seeds"]):
        raise ValueError("validation seeds do not match V7.3 freeze")
    device = torch.device("cuda")
    tensor_keys = (*REPRESENTATION_KEYS,
                   *(target_key(value) for value in horizons), "legal")
    for data in (train, validation):
        for key in tensor_keys:
            data[key] = data[key].to(device)
    architecture = protocol["critic"]["architecture"]
    reports, artifacts = {}, {}
    pass_matrix = {key: {} for key in REPRESENTATION_KEYS}
    for horizon_index, horizon in enumerate(horizons):
        key = target_key(horizon)
        reports[str(horizon)] = {}
        artifacts[str(horizon)] = {}
        train_target = {"return": train[key], "legal": train["legal"]}
        validation_target = {
            "return": validation[key], "legal": validation["legal"]}
        for representation_index, name in enumerate(REPRESENTATION_KEYS):
            report, artifact = train_representation(
                f"{name}@{horizon}", train[name], validation[name],
                train_target, validation_target, architecture,
                protocol["critic"],
                args.seed + horizon_index * 10000 + representation_index * 1000)
            gates = gate_metrics(
                report["best_validation_metrics"], protocol["gates"])
            passed = all_pass(gates)
            report["gates"] = gates
            report["all_gates_pass"] = passed
            reports[str(horizon)][name] = report
            artifacts[str(horizon)][name] = artifact
            pass_matrix[name][str(horizon)] = passed
            print(json.dumps({
                "horizon": horizon,
                "representation": name,
                "pairwise_accuracy": report["best_validation_metrics"][
                    "pairwise_accuracy"],
                "normalized_argmax_regret": report[
                    "best_validation_metrics"]["normalized_argmax_regret"],
                "all_gates_pass": passed,
            }), flush=True)
    decision, selected_horizon, response_target_development_authorized = decide(
        pass_matrix, protocol["gates"]["minimum_research_horizon"])
    summary = {
        "suite": "DRVOI-RHPPO-V7.3-return-horizon-development",
        "protocol_version": protocol["protocol_version"],
        "scientific_result": False,
        "formal_test_accessed": False,
        "train_seeds": train_seeds,
        "validation_seeds": validation_seeds,
        "train_contexts": int(train["legal"].shape[0]),
        "validation_contexts": int(validation["legal"].shape[0]),
        "horizons": horizons,
        "architecture": architecture,
        "results": reports,
        "pass_matrix": pass_matrix,
        "decision": decision,
        "selected_horizon": selected_horizon,
        "response_target_development_authorized": (
            response_target_development_authorized),
        "formal_test_generation_authorized": False,
        "p1q_authorized": False,
        "o0_authorized": False,
        "long_training_authorized": False,
        "config_sha256": config_hash,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    torch.save({
        "protocol_version": protocol["protocol_version"],
        "architecture": architecture,
        "horizons": horizons,
        "artifacts": artifacts,
        "decision": decision,
        "selected_horizon": selected_horizon,
    }, args.output.with_suffix(".pt"))
    print(json.dumps({
        "decision": decision,
        "selected_horizon": selected_horizon,
        "response_target_development_authorized": (
            response_target_development_authorized),
    }))
    if not response_target_development_authorized:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
